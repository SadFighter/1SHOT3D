import type { ScenePayload } from '../types';

const RUNTIME_HEAD = `
<script type="importmap">
{
  "imports": {
    "three": "https://unpkg.com/three@0.169.0/build/three.module.js",
    "three/addons/": "https://unpkg.com/three@0.169.0/examples/jsm/"
  }
}
</script>
`;

const RUNTIME_BODY = `
<script type="module">
import * as THREE from 'three';
import { OrbitControls } from 'three/addons/controls/OrbitControls.js';

const payload = JSON.parse(document.getElementById('scene-payload').textContent);

const canvas = document.getElementById('c');
const renderer = new THREE.WebGLRenderer({ canvas, antialias: true, alpha: false });
renderer.setPixelRatio(Math.min(window.devicePixelRatio, 2));
renderer.shadowMap.enabled = true;

const scene = new THREE.Scene();
scene.background = new THREE.Color(0x1a1a1f);

const camera = new THREE.PerspectiveCamera(50, 1, 0.1, 1000);
camera.position.set(
  payload.camera.position.x,
  payload.camera.position.y,
  payload.camera.position.z
);

const controls = new OrbitControls(camera, canvas);
controls.target.set(
  payload.camera.target.x,
  payload.camera.target.y,
  payload.camera.target.z
);
controls.enableDamping = true;
controls.update();

scene.add(new THREE.AmbientLight(0xffffff, 0.6));
const dir = new THREE.DirectionalLight(0xffffff, 1.2);
dir.position.set(5, 10, 7);
dir.castShadow = true;
dir.shadow.mapSize.set(1024, 1024);
scene.add(dir);

const grid = new THREE.GridHelper(20, 20, 0x555555, 0x333333);
grid.material.opacity = 0.4;
grid.material.transparent = true;
scene.add(grid);

for (const obj of payload.objects) {
  let geo;
  switch (obj.kind) {
    case 'box':      geo = new THREE.BoxGeometry(1, 1, 1); break;
    case 'sphere':   geo = new THREE.SphereGeometry(0.6, 32, 16); break;
    case 'plane':    geo = new THREE.PlaneGeometry(2, 2); break;
    case 'cylinder': geo = new THREE.CylinderGeometry(0.5, 0.5, 1, 32); break;
    default: continue;
  }
  const mat = new THREE.MeshStandardMaterial({
    color: new THREE.Color(obj.color),
    side: obj.kind === 'plane' ? THREE.DoubleSide : THREE.FrontSide,
  });
  const mesh = new THREE.Mesh(geo, mat);
  mesh.position.set(obj.position.x, obj.position.y, obj.position.z);
  mesh.rotation.set(obj.rotation.x, obj.rotation.y, obj.rotation.z);
  mesh.scale.set(obj.scale.x, obj.scale.y, obj.scale.z);
  mesh.castShadow = true;
  mesh.receiveShadow = true;
  scene.add(mesh);
}

function resize() {
  const w = window.innerWidth;
  const h = window.innerHeight;
  renderer.setSize(w, h, false);
  camera.aspect = w / h;
  camera.updateProjectionMatrix();
}
window.addEventListener('resize', resize);
resize();

let running = true;

window.addEventListener('message', (e) => {
  const msg = e.data;
  if (!msg || typeof msg !== 'object') return;
  if (msg.type === 'setCamera' && Array.isArray(msg.position)) {
    camera.position.set(msg.position[0], msg.position[1], msg.position[2]);
    controls.update();
  }
  if (msg.type === 'setTarget' && Array.isArray(msg.target)) {
    controls.target.set(msg.target[0], msg.target[1], msg.target[2]);
    controls.update();
  }
  if (msg.type === 'pause') running = false;
  if (msg.type === 'resume') running = true;
});

function tick() {
  requestAnimationFrame(tick);
  if (!running) return;
  controls.update();
  renderer.render(scene, camera);
}
tick();

setTimeout(() => document.getElementById('credit')?.classList.add('hide'), 4000);
</script>
`;

export function generateHtml(payload: ScenePayload): string {
  const json = JSON.stringify(payload).replace(/</g, '\\u003c');
  return `<!doctype html>
<!-- Generated by 1SHOT3D — self-contained 3D scene embed -->
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width,initial-scale=1" />
<title>1SHOT3D Scene</title>
<style>
  html, body { margin: 0; height: 100%; overflow: hidden; background: #1a1a1f; }
  #c { display: block; width: 100vw; height: 100vh; }
  #credit {
    position: fixed; bottom: 8px; right: 12px;
    font: 11px system-ui, sans-serif; color: rgba(255,255,255,0.25);
    pointer-events: none; user-select: none;
    transition: opacity 0.6s ease; opacity: 1;
  }
  #credit.hide { opacity: 0; }
</style>
${RUNTIME_HEAD}
</head>
<body>
<canvas id="c"></canvas>
<div id="credit">made with 1SHOT3D</div>
<script type="application/json" id="scene-payload">${json}</script>
${RUNTIME_BODY}
</body>
</html>`;
}